import vm from 'node:vm';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const context=vm.createContext({});
for(const name of ['link-core','search-core','editing-core'])vm.runInContext(readFileSync(new URL('../dist/'+name+'.js',import.meta.url),'utf8'),context);
const {AmagoEditing:E}=context;
const docs=Array.from({length:41},(_,i)=>({body:'#tag'+String(i).padStart(2,'0')+' #comum',tags:['comum']}));
assert.equal(E.tagPage(docs).items.length,12);
assert.equal(E.tagPage(docs).total,42);
assert.equal(E.tagPage(docs).items.find(([tag])=>tag==='comum')[1],41);
assert.equal(E.tagPage(docs,'',999).page,3);
assert.equal(E.tagPage(docs,'tag40',2).page,0);
assert.equal(E.tagPage(docs,'inexistente').items.length,0);
assert.equal(E.tagPage([{tags:['reflexões']}],'reflexoes').total,1);
const first={path:'A.md',body:'Primeiro rascunho A',version:'a0',savedBody:'Original A',dirty:true};
const second={path:'B.md',body:'Rascunho B',version:'b0',savedBody:'Original B',dirty:true};
let release;const gate=new Promise(r=>release=r),writes=[];
const adapter={async save(path,body,version){writes.push({path,body,version});if(writes.length===1)await gate;return {version:version+'+'}}};
const pending=E.saveDraft(first,adapter);
await Promise.resolve();await Promise.resolve();
first.body='Nova edição A durante gravação';
await E.saveDraft(second,adapter);
release();await pending;
assert.deepEqual(writes.map(x=>x.path),['A.md','B.md','A.md']);
assert.equal(writes[2].version,'a0+');
assert.equal(first.savedBody,'Nova edição A durante gravação');assert.equal(first.dirty,false);
assert.equal(second.savedBody,'Rascunho B');assert.equal(second.dirty,false);
first.body='Preservar rascunho';first.dirty=true;
await E.saveDraft(first,{save:async()=>({conflict:true})});
assert.equal(first.body,'Preservar rascunho');assert.equal(first.dirty,true);assert.equal(first.conflict,true);assert.equal(first.version,'a0++');
await E.saveDraft(first,{save:async()=>{throw Error('Sem acesso')}});
assert.equal(first.error,'Sem acesso');assert.equal(first.dirty,true);
await E.saveDraft(first,{save:async()=>({version:'recovered'})});
assert.equal(first.dirty,false);assert.equal(first.conflict,false);assert.equal(first.error,null);
let count=0;first.body='Edição concorrente';first.dirty=true;
await Promise.all([E.saveDraft(first,{save:async()=>{count++;return {version:'once'}}}),E.saveDraft(first,{save:async()=>{count++;return {version:'twice'}}})]);
assert.equal(count,1);
console.log('Studio: bounded/searchable tags, isolated drafts, edits during save, concurrent saves, conflicts and recovery passed.');
