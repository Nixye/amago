import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context=vm.createContext({localStorage:{getItem:()=>null,setItem:()=>{}},document:{querySelector:()=>({innerHTML:'',textContent:''})},console,crypto:globalThis.crypto,structuredClone,setTimeout,clearTimeout,window:{}});
const base=readFileSync(new URL('../dist/app.js',import.meta.url),'utf8');
const enhancement=readFileSync(new URL('../dist/refinement.js',import.meta.url),'utf8');
vm.runInContext(base.slice(0,base.indexOf("document.addEventListener('click'")),context);
vm.runInContext(enhancement.slice(0,enhancement.indexOf("document.addEventListener('click'")),context);
const run=s=>vm.runInContext(s,context);
assert.ok(run('metrics().edges')>0);
assert.ok(run('tasks().length')>0);
const previous=run('note().body');run('note().body="Uma alteração que precisa ser recuperável"; persist()');
assert.equal(run('vault.history[note().id][0].body'),previous);
run('note().body="Segunda alteração próxima"; persist()');assert.equal(run('vault.history[note().id].length'),1);
run('vault.history[note().id][0].savedAt=new Date(Date.now()-31000).toISOString(); note().body="Terceira alteração";persist()');assert.equal(run('vault.history[note().id].length'),2);
assert.equal(run('vault.history[note().id][1].body'),'Segunda alteração próxima');
assert.notEqual(run('uniqueTitle(note().title)'),run('note().title'));
run('for(let i=0;i<30;i++){vault.history[note().id].at(-1).savedAt=new Date(0).toISOString();note().body="Edit "+i;persist()}');assert.equal(run('vault.history[note().id].length'),20);
assert.equal(run('templates.length'),4);
console.log('Refinement checks passed: task aggregation, real graph edges, recoverable history, coalescing, retention, unique names, templates.');
