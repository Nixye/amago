import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const filename=new URL('./dist/app.js',import.meta.url);
const source=readFileSync(filename,'utf8');
const field={innerHTML:'',textContent:''};let saved;
const context=vm.createContext({localStorage:{getItem:()=>null,setItem:(_,v)=>saved=v},document:{querySelector:()=>field},console,crypto:globalThis.crypto,setTimeout,clearTimeout});
vm.runInContext(source.slice(0,source.indexOf("document.addEventListener('click'")),context);
const run=code=>vm.runInContext(code,context);
assert.match(run('markdown("## Uma ideia\\n\\n**forte** e *leve*")'),/<h2[^>]*>Uma ideia<\/h2>.*<strong>forte<\/strong> e <em>leve<\/em>/s);
assert.equal(run('inline("`[[texto]]`")'),'<code>[[texto]]</code>');
assert.equal(run('inline("[[pasta/nota#Seção|Rótulo]]")'),'<button class="wiki-link" data-wiki="pasta/nota#Seção">Rótulo</button>');
assert.equal(run('inline("<img src=x onerror=alert(1)>")'), '&lt;img src=x onerror=alert(1)&gt;');
assert.ok(!run('inline("[abrir](javascript:alert)")').includes('<a '));
assert.match(run('markdown("- [ ] Fazer\\n- [x] Feito")'),/data-task="0".*data-task="1"/s);
assert.equal(run('links({body:"`[[Exemplo]]` e [[Jardim de ideias]]"}).length'),1);
assert.ok(run('backlinks(findTitle("Jardim de ideias")).length')>=3);
run('persist()');assert.equal(JSON.parse(saved).notes.length,7);
const root=new URL('./dist/',import.meta.url);
for(const f of ['index.html','style.css','app.js'])assert.ok(readFileSync(new URL(f,root)).length>0);
console.log('9 checks passed: Markdown, code literals, HTML escaping, safe links, tasks, wiki links, backlinks, persistence and assets.');
